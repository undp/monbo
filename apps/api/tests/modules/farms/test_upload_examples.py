"""The upload step's example files upload without errors.

They are generated by apps/web/scripts/generate-upload-examples.py into
apps/web/public/files/examples/{es,en}/. Here each geo file goes through
`/farms/import` (GDAL, as in production), and every option's farms, all together,
through `/farms/parse`. The web's readers (the Excel loader, the attribute names
and the join by ID) are checked on the same files by
apps/web/src/utils/uploadExamples.test.ts.
"""

from pathlib import Path
from typing import Any

import pytest
from fastapi.testclient import TestClient

from app.main import app
from tests.regression.pipeline import read_farm_rows

client = TestClient(app)

# Found from the repository root; missing when only apps/api is available (the API
# dev container), as in tests/regression/test_regression.py.
_EXAMPLES = Path("apps/web/public/files/examples")
EXAMPLES_DIR = next(
    (
        root / _EXAMPLES
        for root in Path(__file__).resolve().parents
        if (root / _EXAMPLES).is_dir()
    ),
    None,
)
pytestmark = pytest.mark.skipif(
    EXAMPLES_DIR is None, reason="apps/web is not available"
)

FILES = {
    "es": {
        "option1": "opcion-1-plantilla-con-coordenadas.xlsx",
        "geojson": "opcion-2-fincas.geojson",
        "shapefile": "opcion-2-fincas-shapefile.zip",
        "kml": "opcion-3-poligonos.kml",
        "option3": "opcion-3-datos-produccion.xlsx",
    },
    "en": {
        "option1": "option-1-template-with-coordinates.xlsx",
        "geojson": "option-2-farms.geojson",
        "shapefile": "option-2-farms-shapefile.zip",
        "kml": "option-3-polygons.kml",
        "option3": "option-3-production-data.xlsx",
    },
}
LANGUAGES = list(FILES)
GEO_FILES = ["geojson", "shapefile", "kml"]
# Any country: the examples carry none, so they upload under the selected one
COUNTRY = "CR"

# The attribute names the examples use, lowercased, by the row key they fill (the
# web's geoAttributeMappings accepts these and more).
ATTRIBUTES = {
    "id": ("id",),
    "producerName": ("producername", "productor"),
    "productionDate": ("productiondate", "fecha_prod"),
    "productionQuantity": ("productionquantity", "cantidad"),
    "productionQuantityUnit": ("productionquantityunit", "unidad"),
    "cropType": ("croptype", "cultivo"),
    "area": ("area", "area_ha"),
    "region": ("region",),
    "association": ("association", "asociacion"),
}
COUNTRY_ATTRIBUTES = {"producercountry", "pais", "país", "country"}


def _path(language: str, example: str) -> Path:
    assert EXAMPLES_DIR is not None
    return EXAMPLES_DIR / language / FILES[language][example]


def _import(language: str, example: str) -> dict[str, Any]:
    path = _path(language, example)
    response = client.post(
        "/farms/import", files={"file": (path.name, path.read_bytes())}
    )
    assert response.status_code == 200, response.text
    return response.json()


def _geometry(feature: dict[str, Any]) -> dict[str, Any]:
    return {
        "coordinatesFormat": "WKT",
        "geometryType": feature["geometryType"],
        "farmCoordinates": feature["farmCoordinates"],
    }


def _attribute_row(feature: dict[str, Any]) -> dict[str, Any]:
    """Option 2: a farm's data from its feature's attributes."""
    properties = {name.lower(): value for name, value in feature["properties"].items()}
    row: dict[str, Any] = {
        key: next((properties[n] for n in names if properties.get(n) is not None), None)
        for key, names in ATTRIBUTES.items()
    }
    return {**row, **_geometry(feature), "country": COUNTRY, "documents": []}


def _excel_rows(language: str, example: str) -> list[dict[str, Any]]:
    return [
        {**row, "country": COUNTRY} for row in read_farm_rows(_path(language, example))
    ]


def _joined_rows(language: str) -> list[dict[str, Any]]:
    """Option 3: the KML's geometry, joined to the Excel row by placemark name."""
    features = {
        feature["properties"]["Name"]: feature
        for feature in _import(language, "kml")["features"]
    }
    rows = _excel_rows(language, "option3")
    assert sorted(row["id"] for row in rows) == sorted(features)
    return [{**row, **_geometry(features[row["id"]])} for row in rows]


@pytest.mark.parametrize("language", LANGUAGES)
@pytest.mark.parametrize("example", GEO_FILES)
def test_geo_examples_import_without_errors(language, example):
    imported = _import(language, example)

    features = imported["features"]
    assert [feature["errors"] for feature in features] == [[]] * len(features)
    types = sorted(feature["geometryType"] for feature in features)
    assert types == ["Point"] + ["Polygon"] * 4
    for feature in features:
        names = {name.lower() for name in feature["properties"]}
        assert not names & COUNTRY_ATTRIBUTES


@pytest.mark.parametrize("language", LANGUAGES)
def test_kml_names_are_the_ids_and_carry_nothing_else(language):
    for feature in _import(language, "kml")["features"]:
        properties = feature["properties"]
        assert properties["Name"].startswith("E3-")
        assert {name: value for name, value in properties.items() if value} == {
            "Name": properties["Name"]
        }


@pytest.mark.parametrize("language", LANGUAGES)
def test_every_example_parses_together(language):
    rows = [
        *_excel_rows(language, "option1"),
        *(_attribute_row(f) for f in _import(language, "geojson")["features"]),
        *(_attribute_row(f) for f in _import(language, "shapefile")["features"]),
        *_joined_rows(language),
    ]

    response = client.post(f"/farms/parse?locale={language}", json=rows)

    assert response.status_code == 200, response.text
    farms = response.json()
    ids = [farm["id"] for farm in farms]
    assert len(ids) == len(set(ids)) == 20
    assert {farm["id"][:2] for farm in farms} == {"E1", "E2", "E3"}
    points = [farm for farm in farms if farm["polygon"]["type"] == "point"]
    assert len(points) == 4
    # A point's area is the 2.5 ha the example declares
    assert {point["polygon"]["area"] for point in points} == {25000.0}
    assert all(farm["country"] == COUNTRY for farm in farms)
